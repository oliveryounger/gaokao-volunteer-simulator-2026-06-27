    const letter = String.fromCharCode(65 + i);
    if (!slot) {
      timeline.push([`${letter} 志愿`, "空志愿，直接跳过。"]);
      continue;
    }
    const school = schools.find((item) => item.code === slot.code);
    const line = schoolLine(school);
